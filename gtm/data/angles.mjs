// Renders the canonical angle library (02), the 124-angle reconciliation (14) and the long-tail placement map (16)
// from angle-library.csv + angle-sources.csv. Edit the CSVs, then: node gtm/data/angles.mjs   (--check fails on drift)
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseCsv } from './csv.mjs';

const dir = import.meta.dirname, gtm = resolve(dir, '..');
const table = file => { const [head, ...rows] = parseCsv(readFileSync(resolve(dir, file), 'utf8')); return rows.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? '']))); };
export const angles = table('angle-library.csv');
export const sources = table('angle-sources.csv');

export const CLASSES = ['CORE', 'VERTICAL', 'OBJECTION', 'TRUST', 'ECONOMICS', 'ACQUISITION', 'RETENTION', 'OPERATIONS', 'FUTURE'];
export const STATUSES = { 'SELL NOW': 'SELL NOW', 'RC READY': 'RC READY — not deployed', QUALIFIED: 'QUALIFIED / PREVIEW', FUTURE: 'FUTURE / DO NOT SELL YET' };
export const USES = { 'walk-in': 'Walk-in', demo: 'Demo', 'static-ad': 'Static ad', video: 'Video', content: 'Content', retargeting: 'Retargeting', 'follow-up': 'Sales follow-up', faq: 'FAQ', 'vertical-page': 'Vertical page', homepage: 'Homepage', onboarding: 'Onboarding', 'trust-collateral': 'Trust collateral', 'learning-log': 'Learning log (demand signal)', outlook: 'Ausblick line only' };
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const srcList = a => [a.sources, a.previous && `prev ${a.previous.replace(/;/g, ', ')}`].filter(Boolean).join(' · ').replace(/;/g, ', ');
const uses = a => a.use.split(';').map(u => USES[u] ?? u).join(', ');

function library() {
  const out = ['<!-- generated by gtm/data/angles.mjs from data/angle-library.csv — edit the CSV, not this block -->', ''];
  const count = (k, v) => angles.filter(a => a[k] === v).length;
  out.push(`**${angles.length} canonical angles** after merging the original 124-angle bank, its priority matrix, verticals, ads, content scenarios and objection bank (169 traced source items, see [14-angle-reconciliation.md](14-angle-reconciliation.md)) with the rebuilt bank from the previous pass.`, '');
  out.push('| Class | Angles | | Status | Angles |', '|---|---|---|---|---|');
  const st = Object.keys(STATUSES);
  for (let i = 0; i < Math.max(CLASSES.length, st.length); i++) out.push(`| ${CLASSES[i] ?? ''} | ${CLASSES[i] ? count('class', CLASSES[i]) : ''} | | ${st[i] ? STATUSES[st[i]] : ''} | ${st[i] ? count('status', st[i]) : ''} |`);
  out.push('', '### Index', '', '| ID | Angle | Class | Status | Used in |', '|---|---|---|---|---|');
  for (const c of CLASSES) for (const a of angles.filter(x => x.class === c)) out.push(`| ${a.id} | ${cell(a.name)} | ${a.class} | ${STATUSES[a.status]} | ${uses(a)} |`);
  for (const c of CLASSES) {
    out.push('', `### ${c}`, '');
    for (const a of angles.filter(x => x.class === c)) {
      out.push(`#### ${a.id} · ${a.name}`, `**${STATUSES[a.status]}**${a.disposition === 'deferred' ? ' · deferred / unsuitable for now' : ''} · sources: ${srcList(a) || '—'}`, '');
      const f = [['Merchant pain', a.pain], ['Commercial outcome', a.outcome], ['Strongest hook', a.hook], ['Strongest verticals', a.verticals], ['Best channel', a.channel], ['Sales/demo proof', a.proof], ['Objection addressed', a.objection], ['CTA', a.cta], ['Used in', uses(a)], ['Boundary', a.qualifier]];
      for (const [k, v] of f) if (v && v !== '—') out.push(`- **${k}:** ${v}`);
      out.push('');
    }
  }
  return out.join('\n').trimEnd();
}

function reconciliation() {
  const by = id => angles.find(a => a.id === id);
  const out = ['# 14 · Reconciliation: original 124-angle bank → canonical library', '', '<!-- generated by gtm/data/angles.mjs from data/angle-sources.csv -->', '',
    'Source: *Loynara Marketing & Acquisition Playbook* (Appendix A, 124 angles; plus its priority matrix, vertical lines, ads A–E, the „Was würdest du tun?“ scenarios, objection bank B and the merchant-referral line of §6). Compared against the rebuilt bank at commit `5364478`.', '',
    '**Coverage before this pass** means: was the original idea already in the GTM system at `5364478`? *represented* = the same merchant motivation existed; *partial* = touched but not as its own angle or with the wrong evidence state; *missing* = absent.', ''];
  const o = sources.filter(s => s.source_id.startsWith('O'));
  const c = k => o.filter(s => s.coverage_before === k).length;
  out.push(`| Appendix A (124) | Count |`, '|---|---|', `| Already represented | ${c('represented')} |`, `| Partially represented | ${c('partial')} |`, `| Missing | ${c('missing')} |`, `| Merged into canonical angles | ${new Set(o.map(s => s.merged_into)).size} distinct angles |`, '');
  const st = k => o.filter(s => s.status === k).length;
  out.push('| Status of the 124 after merge | Count |', '|---|---|', ...Object.keys(STATUSES).map(k => `| ${STATUSES[k]} | ${st(k)} |`), '');
  out.push('## Appendix A — all 124', '', '| # | Original angle | Coverage before | Merged into | Status |', '|---|---|---|---|---|');
  for (const s of o) out.push(`| ${s.source_id.slice(1)} | **${cell(s.original)}** — ${cell(s.detail)} | ${s.coverage_before} | ${s.merged_into} ${cell(by(s.merged_into).name)} | ${STATUSES[s.status]} |`);
  out.push('', '## Other sections of the original playbook', '', '| Source | Item | Coverage before | Merged into | Status |', '|---|---|---|---|---|');
  for (const s of sources.filter(x => !x.source_id.startsWith('O'))) out.push(`| ${s.section} | **${cell(s.original)}**${s.detail ? ' — ' + cell(s.detail) : ''} | ${s.coverage_before} | ${s.merged_into} ${cell(by(s.merged_into).name)} | ${STATUSES[s.status]} |`);
  out.push('', '## Non-angle parts of the original, and where they went', '',
    '| Original section | Where it lives now |', '|---|---|',
    '| §1 Positioning, umbrella „Keep the customers you earned…“, See → Understand → Act | [02](02-positioning-angles.md) positioning + message hierarchy (evidence-tagged) |',
    '| §2 Claim legend NOW / PARTIAL / WHEN ENABLED / FUTURE | Replaced by LIVE NOW / RC READY / QUALIFIED / FUTURE in [01](01-product-truth.md) |',
    '| §5 Cold DM / WhatsApp system and per-angle DM lines | Kept as **permitted follow-up and inbound-reply** texts in [05](05-sales-playbook.md); not used as cold first contact (Loynara policy) |',
    '| §6 First-100 acquisition stack | [04](04-funnel.md) month-one scenarios + [README](README.md) operating plan |',
    '| §8 Sales-demo structure | [06](06-demo-script.md) (identical order; „Future action“ step stays an Ausblick sentence) |',
    '| §10 Channel × angle plan | [16-execution-matrix.md](16-execution-matrix.md) |',
    '| §11 Message hierarchy | [02](02-positioning-angles.md), levels 4–5 tagged by evidence state |',
    '| §12 „Was würdest du tun?“ content | [09](09-content-calendar.md) series; scenarios that need FUTURE capabilities are labelled Ausblick |',
    '| Final rule „lead with the business problem, show one mechanism, prove the workflow“ | Walk-in and demo structure in [05](05-sales-playbook.md) / [06](06-demo-script.md) |', '',
    '## Corrections to the original', '',
    '- The original lists NFC tapping as live in P6, P7 and Ad D („NFC antippen oder QR scannen“). Physical NFC acceptance has not passed, so these are QR-first now and NFC is CORE-11 (QUALIFIED / PREVIEW) with a prepared copy switch.',
    '- The original treats corrections and card reissue as live („NOW AFTER HARDENING“). They are in the merchant-completion RC, not deployed: OPS-02/03/04 are RC READY, with today\'s live path stated next to them.',
    '- „Know who returns“ (P9) is QUALIFIED: the live customer list is pseudonymous („Namen und Kontaktdaten zeigt Loynara hier nicht“), so the owner sees cards and counts, not names.',
    '- No original angle was dropped. Deferred/unsuitable for now: ECO-05 founding merchant (commercial terms), FUT-05 birthday (no data basis), FUT-19 packages (financial complexity), FUT-21 review request (never incentivised), VER-06/07/08 lower-fit verticals.');
  return out.join('\n') + '\n';
}

function placements() {
  const out = ['<!-- generated by gtm/data/angles.mjs from data/angle-library.csv -->', '', '| Placement | Angles |', '|---|---|'];
  for (const [k, label] of Object.entries(USES)) {
    const ids = angles.filter(a => a.class !== 'CORE' && a.use.split(';').includes(k)).map(a => `${a.id}`);
    if (ids.length) out.push(`| ${label} | ${ids.join(', ')} |`);
  }
  return out.join('\n');
}

const between = (file, body) => {
  const path = resolve(gtm, file), text = readFileSync(path, 'utf8'), a = '<!-- angles:start -->', b = '<!-- angles:end -->';
  if (!text.includes(a) || !text.includes(b)) throw new Error(`${file} lacks the ${a} / ${b} markers`);
  return [path, text.slice(0, text.indexOf(a) + a.length) + '\n' + body + '\n' + text.slice(text.indexOf(b))];
};
export function render() {
  return [between('02-positioning-angles.md', library()), [resolve(gtm, '14-angle-reconciliation.md'), reconciliation()], between('16-execution-matrix.md', placements())];
}

if (process.argv[1] === import.meta.filename) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [path, text] of render()) {
    let current = ''; try { current = readFileSync(path, 'utf8'); } catch {}
    if (current !== text) { stale++; if (!check) writeFileSync(path, text); }
  }
  if (check && stale) { console.error(`${stale} generated angle file(s) are stale: run node gtm/data/angles.mjs`); process.exit(1); }
  console.log(check ? 'angle docs up to date' : `wrote ${stale} file(s); ${angles.length} angles, ${sources.length} sources`);
}
