import { randomUUID } from "node:crypto";
import { afterAll, beforeEach, expect, it } from "vitest";
import { pool } from "@/db";
import { nfcFixture } from "./nfc-test-db";
import { award, reverseEntry } from "./loyalty";
import { getMerchantAnalytics } from "./merchant-analytics";
import { getRetentionSummary } from "./retention";
const database = new URL(process.env.DATABASE_URL ?? "http://invalid");
if (!["localhost","127.0.0.1"].includes(database.hostname) || database.pathname !== "/looplocal_test" || database.username !== "looplocal") throw new Error("Synthetic analytics database required");
beforeEach(async () => { await pool.query('TRUNCATE TABLE tenants, "user", demo_requests CASCADE'); });
afterAll(async () => { await pool.end(); });
it("keeps one partially corrected request as one checkout and drops it only when fully corrected", async () => {
  const own = await nfcFixture(), foreign = await nfcFixture();
  const requestId = randomUUID();
  const input = { userId: own.userId, locationId: own.location.id, membershipId: own.member.id, quantity: 1, requestId, idempotencyKey: randomUUID() };
  const first = await award(input); expect(await award(input)).toMatchObject({ duplicate: true, entryId: first.entryId });
  const second = await award({ ...input, quantity: 2, idempotencyKey: randomUUID() });
  await award({ userId: foreign.userId, locationId: foreign.location.id, membershipId: foreign.member.id, quantity: 5, requestId: randomUUID(), idempotencyKey: randomUUID() });
  const report = () => getMerchantAnalytics(own.userId, { windowDays: 30 });
  expect(await report()).toMatchObject({ qualifyingCheckouts: 1, participatingCards: 1, repeatCards: 0, issued: { awardActions: 2, stampUnits: 3 } });
  const reverse = (entryId: string) => reverseEntry({ userId: own.userId, locationId: own.location.id, entryId, reason: "Synthetic counting correction", requestId: randomUUID(), idempotencyKey: randomUUID() });
  await reverse(first.entryId);
  expect(await report()).toMatchObject({ qualifyingCheckouts: 1, repeatCards: 0, issued: { awardActions: 1, stampUnits: 2 } });
  await award({ ...input, requestId: randomUUID(), idempotencyKey: randomUUID() });
  expect(await report()).toMatchObject({ qualifyingCheckouts: 2, repeatCards: 1 });
  await reverse(second.entryId);
  expect(await report()).toMatchObject({ qualifyingCheckouts: 1, repeatCards: 0 });
  expect(await getRetentionSummary(own.userId)).toMatchObject({ openCards: 1, recent: 1, drifting: 0, never: 0 });
  const before = (await pool.query('SELECT id,balance FROM memberships ORDER BY id')).rows;
  await report(); await getRetentionSummary(own.userId);
  expect((await pool.query('SELECT id,balance FROM memberships ORDER BY id')).rows).toEqual(before);
});
